/* =============================================================================
   build.mjs: builds the standalone Byman Cykler placeholder page
   =============================================================================

   WHAT THIS DOES (plain words)
   ----------------------------
   It reads three files and writes a finished web page into the folder build/:
     data/business.json   name, address, phone, email, opening hours, special hours
     data/brands.json     the brand logos, in the order they appear on the page
     design/copy-da.md    every Danish text on the page (the "## Strings" block)
   It also makes web-sized versions of the shop photo (build/img/) and copies the
   design tokens (design/tokens.css -> build/tokens.css).
   Nothing is downloaded and nothing is installed. Only Node is needed.

   What ends up in build/:
     index.html   GENERATED by this script. Don't edit it by hand: your change
                  would be lost the next time someone runs the build.
     tokens.css   GENERATED copy of design/tokens.css (the Press colours, fonts, sizes).
     styles.css   hand-written page styles (ui-spec.md). This script never touches it.
     app.js       hand-written script: "Åbent nu" status, today's row, special-hours
                  notice, pause button. This script never touches it.
     img/         GENERATED photo versions and PNG logo copies.
   The build/ folder only uses relative links, so it can be uploaded on its own.

   HOW TO RUN IT
   -------------
   Open Terminal and type ONE of these, then press Enter:
     node placeholder/build.mjs     (when you are in the Byman-cykler folder)
     node build.mjs                 (when you are in the placeholder folder)
   It prints what it did. If something is wrong in the data, it stops without
   changing the page and tells you (in Danish and English) what to fix.

   HOW TO ADD A BRAND
   ------------------
   1. Put the logo file in placeholder/assets/logos/. Best: an SVG that uses
      fill="currentColor". Also fine: a white or black PNG on a transparent background.
      Only use official logo files (the brand's own website or press kit).
   2. In data/brands.json, copy one existing entry (from { to }) and change at least
      "name", "slug" (short, lowercase, no spaces, e.g. "dt-swiss"), "logo" (the file
      path) and "scale" (1 = normal size; bigger number = bigger logo).
      The order in the file is the order on the page.
   3. Run the build again. With 12 or more logos the grid switches to 6 per row on
      wide screens by itself, and the "…og mange flere" box always fills the last row.

   HOW TO SWAP THE PHOTO
   ---------------------
   1. Put the new photo in placeholder/assets/img/ (JPEG or PNG). Ideal: landscape,
      daylight, at least 2400 px wide, ideally 3600 x 2025 (16:9), with the BYMAN sign
      and the door in the middle third of the picture.
   2. Change PHOTO_FILE below to the new file name.
   3. Change "photo.alt" in design/copy-da.md so it describes the NEW photo (it is
      read aloud to blind visitors and shown if the photo can't load).
      Tip: phone photos can hide the place and time they were taken. On the Mac, open the
      photo in Preview, choose Tools → Show Inspector → (i) → GPS → Remove Location Info.
      Only use a photo the shop owns (not from Google Maps, Street View or review sites).
   4. Run the build ON THE MAC (it uses the Mac's built-in "sips" tool to make the
      smaller AVIF and JPEG versions). The page then picks the layout by itself: a
      photo at least 2400 px wide and landscape fills the full width; a smaller photo
      is shown smaller, so it never looks blurry. The versions are kept in build/img/
      and reused, so a later build on a computer without "sips" still works.

   HOW TO ADD SPECIAL OPENING HOURS (holidays, stock-taking, ...)
   --------------------------------------------------------------
   In data/business.json, "specialHours" is a list. Add one entry per date:
       "specialHours": [
         { "date": "2026-12-24", "closed": true, "note": "God jul." },
         { "date": "2026-12-23", "open": "10:00", "close": "13:00", "closed": false }
       ]
   - "date" is YEAR-MONTH-DAY. Times are HH:MM with a colon (the page shows "10.00").
   - "note" is optional, a short Danish sentence.
   - From 14 days before the date, the page shows a notice above the hours table, and
     the "Åbent nu" status uses the special hours on that day. Then run the build.
   - Dates that have passed are left out automatically at the next build.

   FONTS
   -----
   The page uses the theme's own fonts, Instrument Serif and Space Mono, from
   assets/fonts/ (copied to build/fonts/). If a font can't load, the browser uses the
   closest system font (Bodoni 72 / Times New Roman and Menlo / Consolas). To change
   the font files, edit FONTS below.

   THE BYMAN LOGO (later)
   ----------------------
   There is no logo file yet, so the name is shown as text. When there is one, put it
   in assets/logos/ (SVG preferred) and set LOGO_FILE below, then run the build.

   BEFORE PUBLISHING THE PAGE: SET PAGE_URL
   ----------------------------------------
   PAGE_URL below is the page's public address. It is empty (null) until Søren has
   chosen where the standalone page will live. While it is empty, the build prints a
   warning and the page has: no canonical link, no og:url, and NO share picture
   (Facebook, Messenger and LinkedIn need a full https:// address for it, and so does
   Google's business data). Set it, e.g. PAGE_URL = 'https://www.example.dk/', and
   build again: the canonical link, og:url, og:image and the JSON-LD image then all
   use full https:// addresses. The address must start with https:// and end with
   "/" (or with the page name, e.g. ".../index.html").

   TEST SWITCHES FOR THE FINISHED PAGE (add to the address, e.g. index.html?now=...)
   ?now and ?special only work on your own computer (localhost, 127.0.0.1, *.localhost,
   or the file opened from disk). On the published page they are ignored, so nobody can
   share a link that shows fake opening hours.
     ?now=2026-10-10T13:30          pretend it is this time in Copenhagen
     ?special=2026-10-10,10:00,12:00  pretend there are special hours that day
     ?special=2026-10-10,closed       (repeat &special=... for more dates;
     ?special=2026-10-10,closed,Note  an optional note goes after the last comma)
     ?nojs=1                        show the page as it looks without JavaScript
                                    (works everywhere; it only shows the plain page)
   ========================================================================== */

