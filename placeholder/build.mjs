// Calendar maths at noon UTC, so summer time never shifts a date.
const utc = (ymd) => new Date(`${ymd}T12:00:00Z`);
const validYmd = (s) => typeof s === 'string' && /^\d{4}-\d{2}-\d{2}$/.test(s) && utc(s).toISOString().slice(0, 10) === s;
function todayIn(tz) {
  const p = {};
  new Intl.DateTimeFormat('en-GB', { timeZone: tz, year: 'numeric', month: '2-digit', day: '2-digit' })
    .formatToParts(new Date()).forEach((x) => { p[x.type] = x.value; });
  return `${p.year}-${p.month}-${p.day}`;
}

/* ---------- Image sizes, read in plain Node (works on Mac, Linux and Vercel) ---------- */

function imageInfo(buf) {
  // PNG: width and height are bytes 16-23. Colour type (byte 25) 4 or 6, or a tRNS chunk = has transparency.
  if (buf.length > 33 && buf.readUInt32BE(0) === 0x89504e47) {
    let alpha = buf[25] === 4 || buf[25] === 6;
    for (let i = 8; i + 8 <= buf.length && !alpha;) {
      const len = buf.readUInt32BE(i), type = buf.toString('latin1', i + 4, i + 8);
      if (type === 'tRNS') alpha = true;
      if (type === 'IDAT' || type === 'IEND') break;
      i += 12 + len;
    }
    return { type: 'png', width: buf.readUInt32BE(16), height: buf.readUInt32BE(20), alpha, orientation: 1 };
  }
  // JPEG: walk the markers to the "start of frame" (SOF). Also read the EXIF rotation flag.
  if (buf.length > 4 && buf[0] === 0xff && buf[1] === 0xd8) {
    let i = 2, orientation = 1;
    while (i + 9 < buf.length) {
      if (buf[i] !== 0xff) return null;
      const m = buf[i + 1];
      if (m === 0xff) { i++; continue; }
      if (m === 0x01 || (m >= 0xd0 && m <= 0xd8)) { i += 2; continue; }
      const len = buf.readUInt16BE(i + 2);
      if (m === 0xe1 && buf.toString('latin1', i + 4, i + 10) === 'Exif\0\0') orientation = exifOrientation(buf, i + 10) || 1;
      if (m >= 0xc0 && m <= 0xcf && m !== 0xc4 && m !== 0xc8 && m !== 0xcc) {
        return { type: 'jpeg', height: buf.readUInt16BE(i + 5), width: buf.readUInt16BE(i + 7), alpha: false, orientation };
      }
      i += 2 + len;
    }
  }
  return null;
}
function exifOrientation(buf, t) {
  try {
    const le = buf.toString('latin1', t, t + 2) === 'II';
    const u16 = (o) => (le ? buf.readUInt16LE(o) : buf.readUInt16BE(o));
    const u32 = (o) => (le ? buf.readUInt32LE(o) : buf.readUInt32BE(o));
    const ifd = t + u32(t + 4), n = u16(ifd);
    for (let k = 0; k < n; k++) { const e = ifd + 2 + k * 12; if (u16(e) === 0x0112) return u16(e + 8); }
  } catch { /* no readable EXIF: treat as upright */ }
  return 1;
}

