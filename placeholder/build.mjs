function parseAttrs(s) {
  const a = {};
  for (const m of s.matchAll(/([\w:.-]+)\s*=\s*(?:"([^"]*)"|'([^']*)')/g)) a[m[1]] = m[2] ?? m[3];
  return a;
}
const escRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

// Turn an SVG file into safe inline markup that takes the text colour (currentColor).
function inlineSvg(rel, { label, cls, style, idPrefix }) {
  let s = readFileSync(join(ROOT, rel), 'utf8')
    .replace(/<\?xml[\s\S]*?\?>/g, '').replace(/<!DOCTYPE[\s\S]*?>/gi, '').replace(/<!--[\s\S]*?-->/g, '').trim();
  const m = s.match(/^<svg\b([^>]*)>([\s\S]*)<\/svg>$/i);
  if (!m) { fail(`${rel}: kunne ikke læse SVG-filen (starter den med <svg …>?).`, `${rel}: not a readable SVG.`); return null; }
  const attrs = parseAttrs(m[1]);
  let inner = m[2];
  // Safety: an inline SVG becomes part of the page, so no scripts, styles or outside links.
  if (/<script\b|<foreignObject\b|\son\w+\s*=|javascript:/i.test(s)) { fail(`${rel}: SVG-filen indeholder script eller event-kode og bruges ikke.`, `${rel}: contains scripts.`); return null; }
  if (/<style\b/i.test(inner)) { fail(`${rel}: SVG-filen har en <style>-blok, som ville ændre resten af siden. Fjern den og brug fill="currentColor".`, `${rel}: has a <style> block that would leak into the page.`); return null; }
  if (/\b(?:xlink:)?href\s*=\s*["'](?!#)/i.test(inner)) { fail(`${rel}: SVG-filen henter noget udefra (href). Det er ikke tilladt.`, `${rel}: references an outside file.`); return null; }
  // Fixed colours would not follow the page colour: warn.
  const fixed = [...s.matchAll(/\b(?:fill|stroke)\s*[=:]\s*"?\s*(#[0-9a-f]{3,8}|rgb[^;"]*|[a-z]+)/gi)].map((x) => x[1]).filter((v) => !/^(currentColor|none|inherit|evenodd|nonzero)$/i.test(v));
  if (fixed.length) warn(`${rel}: logoet har faste farver (${[...new Set(fixed)].join(', ')}), så det bliver ikke ensfarvet. Brug fill="currentColor".`, `${rel}: has fixed colours.`);
  // <title>/<desc> are replaced by our own label; ids get a unique prefix so two SVGs can never clash.
  inner = inner.replace(/<title\b[\s\S]*?<\/title>/gi, '').replace(/<desc\b[\s\S]*?<\/desc>/gi, '');
  for (const [, id] of inner.matchAll(/\bid\s*=\s*"([^"]+)"/g)) {
    const nid = `${idPrefix}-${id}`, e = escRe(id);
    inner = inner.replace(new RegExp(`(\\bid\\s*=\\s*")${e}"`, 'g'), `$1${nid}"`)
      .replace(new RegExp(`url\\(\\s*#${e}\\s*\\)`, 'g'), `url(#${nid})`)
      .replace(new RegExp(`(href\\s*=\\s*")#${e}"`, 'g'), `$1#${nid}"`);
  }
  inner = inner.replace(/>\s+</g, '><').trim();
  // The shape: from viewBox, else width/height.
  let vb = (attrs.viewBox || '').trim().split(/[\s,]+/).map(Number);
  if (vb.length !== 4 || vb.some((n) => !Number.isFinite(n)) || !(vb[2] > 0 && vb[3] > 0)) {
    const w = parseFloat(attrs.width), h = parseFloat(attrs.height);
    if (!(w > 0 && h > 0)) { fail(`${rel}: SVG-filen har hverken viewBox eller width/height.`, `${rel}: no viewBox or size.`); return null; }
    vb = [0, 0, w, h];
  }
  const keep = ['fill', 'fill-rule', 'clip-rule', 'stroke', 'stroke-width', 'stroke-linecap', 'stroke-linejoin', 'preserveAspectRatio']
    .filter((k) => attrs[k] != null).map((k) => ` ${k}="${esc(attrs[k])}"`).join('');
  const ratio = vb[2] / vb[3];
  return {
    ratio,
    html: `<svg class="${typeof cls === 'function' ? cls(ratio) : cls}" viewBox="${vb.join(' ')}"${keep} role="img" aria-label="${esc(label)}" focusable="false"${style ? ` style="${style(ratio)}"` : ''}>${inner}</svg>`,
  };
}

